import { AnimatePresence, motion } from "framer-motion";
import { ArrowRight } from "lucide-react";
import { useState } from "react";
import { tabPanel } from "@workspace/site-kit";
import { Marker, Rich, TitleBlock } from "./ui";

type Shape = "markdown" | "thoughtform" | "vector";
const SHAPES: Shape[] = ["markdown", "thoughtform", "vector"];

type Kind = "derived" | "generated" | "either";
type Conversion = { kind: Kind; origin: string; text: string };

const FROM_VECTOR =
  "Off by default. An LLM through AgentVault (`POLYTICIAN_LLM_PROVIDER=agentvault`, origin `llm`), given neighbours from the concept's own namespace. A vector can't be decoded back into text.";
const DERIVED = (to: Shape): Conversion => ({
  kind: "derived",
  origin: "derived",
  text: `${to === "vector" ? "The embedding model, in-process." : "A fixed template, in-process."} No LLM, no API key. Origin \`derived\`.`,
});

/** From polytician's README: which conversions derive, which generate, and which can do either. */
const CONVERSIONS: Record<string, Conversion> = {
  "thoughtform→vector": DERIVED("vector"),
  "thoughtform→markdown": DERIVED("markdown"),
  "markdown→vector": DERIVED("vector"),
  "markdown→thoughtform": {
    kind: "either",
    origin: "llm or derived",
    text: "Off by default; turn on one: an LLM through AgentVault (`POLYTICIAN_LLM_PROVIDER=agentvault`, origin `llm`), or the rule-based NLP pipeline (`POLYTICIAN_NLP_PIPELINE=rule-based`, origin `derived`, no LLM).",
  },
  "vector→markdown": { kind: "generated", origin: "llm", text: FROM_VECTOR },
  "vector→thoughtform": { kind: "generated", origin: "llm", text: FROM_VECTOR },
};

const LABEL: Record<Kind, string> = { derived: "Derived", generated: "Generated", either: "Generated or derived" };

function Markers({ kind }: { kind: Kind }) {
  return (
    <span className="inline-flex items-center">
      {kind !== "derived" && <Marker kind="generated" />}
      {kind !== "generated" && <Marker kind="derived" />}
    </span>
  );
}

/** Pick a pair: is that conversion derived locally, generated by a model, or either, as configured? */
export function ConversionMatrix() {
  const [cell, setCell] = useState<[Shape, Shape]>(["markdown", "vector"]);
  const key = `${cell[0]}→${cell[1]}`;
  const conv = CONVERSIONS[key];

  return (
    <div className="panel overflow-hidden">
      <div className="grid lg:grid-cols-[auto_minmax(0,1fr)]">
        <div className="panel-body mx-pad flex flex-col gap-4 md:flex-row md:items-center md:gap-8 lg:flex-col lg:items-start lg:gap-4 lg:border-r lg:border-border">
          <table className="mx">
            <caption className="sr-only">Conversions between the three shapes. Pick a pair for its details.</caption>
            <thead>
              <tr>
                <td className="mx-corner" />
                <th scope="colgroup" colSpan={3} className="mx-head mx-to pb-1">
                  to
                </th>
              </tr>
              <tr>
                <th scope="col" className="mx-head mx-from">
                  from
                </th>
                {SHAPES.map((s) => (
                  <th key={s} scope="col" className="mx-head pb-1">
                    {s}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {SHAPES.map((from) => (
                <tr key={from}>
                  <th scope="row" className="mx-head mx-row">
                    {from}
                  </th>
                  {SHAPES.map((to) => {
                    if (from === to) {
                      return (
                        <td key={to} aria-hidden="true" className="mx-na">
                          <span className="mx-diag" />
                        </td>
                      );
                    }
                    const k = `${from}→${to}`;
                    const c = CONVERSIONS[k];
                    return (
                      <td key={to}>
                        <button
                          type="button"
                          onClick={() => setCell([from, to])}
                          aria-pressed={k === key}
                          aria-label={`${from} to ${to}: ${LABEL[c.kind].toLowerCase()}`}
                          className="mx-cell"
                        >
                          <Markers kind={c.kind} />
                        </button>
                      </td>
                    );
                  })}
                </tr>
              ))}
            </tbody>
          </table>
          <ul className="legend flex-col" aria-label="Legend">
            <li>
              <Marker kind="derived" />
              Derived in-process, no LLM
            </li>
            <li>
              <Marker kind="generated" />
              Generated by an LLM
            </li>
            <li>
              <Markers kind="either" />
              Either, as configured
            </li>
          </ul>
        </div>

        <div className="panel-body border-t border-border lg:border-t-0" aria-live="polite">
          <AnimatePresence mode="wait">
            <motion.div key={key} {...tabPanel} className="flex flex-col gap-4">
              <p className="flex flex-wrap items-center gap-x-2 font-mono text-base text-foreground">
                convert_concept
                <span className="inline-flex items-center gap-2 text-secondary-foreground">
                  {cell[0]}
                  <ArrowRight className="icon text-muted-foreground" aria-hidden="true" />
                  <span className="sr-only">to</span>
                  {cell[1]}
                </span>
              </p>
              <p className="flex items-center gap-2 font-medium text-foreground">
                <Markers kind={conv.kind} />
                {LABEL[conv.kind]}
              </p>
              <p className="text-secondary-foreground">
                <Rich text={conv.text} />
              </p>
              <p className="text-sm text-muted-foreground">
                <Rich text="Never replaces content a caller wrote or imported unless you pass `overwrite: true`. Otherwise: `OVERWRITE_REFUSED`." />
              </p>
            </motion.div>
          </AnimatePresence>
        </div>
      </div>

      <TitleBlock
        label="Conversion title block"
        cells={[
          { k: "call", v: "convert_concept" },
          { k: "from", v: cell[0] },
          { k: "to", v: cell[1] },
          { k: "origin", v: conv.origin },
        ]}
      />
    </div>
  );
}
