import { CopyButton } from "@workspace/site-kit";
import type { ReactNode } from "react";

/** `code` segments between backticks render as inline mono. */
export function Rich({ text }: { text: string }) {
  return (
    <>
      {text.split("`").map((part, i) =>
        i % 2 ? (
          <code key={i} className={part.length > 28 ? "code-inline code-long" : "code-inline"}>
            {part}
          </code>
        ) : (
          part
        ),
      )}
    </>
  );
}

/** A page section: hairline, the shared container, a left-aligned header. */
export function Section({ id, title, lede, children }: { id: string; title: string; lede?: string; children: ReactNode }) {
  return (
    <section id={id} className="section-y border-t border-border">
      <div className="page-container">
        <div className="flex flex-col gap-3">
          <h2 className="text-title">{title}</h2>
          {lede && <p className="text-lead text-secondary-foreground">{lede}</p>}
        </div>
        <div className="mt-8">{children}</div>
      </div>
    </section>
  );
}

/** A statement between sections: section-title size, so it never outranks a heading; a mono caption, no quote marks. */
export function Statement({ children, cite }: { children: ReactNode; cite: string }) {
  return (
    <section className="border-t border-border py-8">
      <div className="page-container">
        <p className="text-title max-w-3xl">{children}</p>
        <p className="text-meta mt-3">{cite}</p>
      </div>
    </section>
  );
}

/**
 * The signature: a thin ruled mono strip at the foot of a product view.
 * Cells hold the constants of the view above it, nothing else.
 */
export function TitleBlock({ label, cells }: { label: string; cells: { k: string; v: string; title?: string }[] }) {
  return (
    <div className="titleblock" role="group" aria-label={label}>
      <dl className="tb-row">
        {cells.map((c) => (
          <div key={c.k} className="tb-cell">
            <dt>{c.k}</dt>
            <dd title={c.title}>{c.v}</dd>
          </div>
        ))}
      </dl>
    </div>
  );
}

/** Filled dot: derived in-process. Ring: generated by a model. Shape, never hue. */
export function Marker({ kind }: { kind: "derived" | "generated" }) {
  return (
    <svg className="marker" viewBox="0 0 16 16" aria-hidden="true">
      {kind === "derived" ? (
        <circle cx="8" cy="8" r="4.5" fill="currentColor" />
      ) : (
        <circle cx="8" cy="8" r="4" fill="none" stroke="currentColor" strokeWidth="1.5" />
      )}
    </svg>
  );
}

/** Ruled term | value cells. `literal` sets the term in mono: a flag, a transport, a tool name. */
export function SpecList({ items }: { items: { term: string; desc: string; literal?: boolean }[] }) {
  return (
    <dl className="spec">
      {items.map((it) => (
        <div key={it.term} className="spec-row">
          <dt className={it.literal ? "lit" : undefined}>{it.term}</dt>
          <dd>
            <p>
              <Rich text={it.desc} />
            </p>
          </dd>
        </div>
      ))}
    </dl>
  );
}

/** A panel with a mono title, a Copy button and mono lines. */
export function CodeBlock({
  title,
  lines,
  prompt = false,
  wrap = false,
}: {
  title: string;
  lines: string[];
  prompt?: boolean;
  wrap?: boolean;
}) {
  return (
    <div className="panel flex flex-col overflow-hidden">
      <div className="panel-header">
        <span className="min-w-0 break-words font-mono">{title}</span>
        <CopyButton
          text={lines.join("\n")}
          label="Copy"
          copiedLabel="Copied"
          ariaLabel={`Copy ${title}`}
          className="btn btn-ghost -my-2 -mr-2 shrink-0 px-2"
        />
      </div>
      <pre tabIndex={0} aria-label={title} className="panel-body grow overflow-x-auto font-mono text-sm leading-6 text-foreground focus-visible:-outline-offset-2">
        {lines.map((line, i) => (
          <div key={i} className={prompt ? "grid grid-cols-[auto_1fr] gap-2" : ""}>
            {prompt && (
              <span aria-hidden className="select-none text-muted-foreground">
                $
              </span>
            )}
            <span className={wrap ? "whitespace-pre-wrap break-words" : "whitespace-pre"}>
              {wrap
                ? line.split(/(?<=[^/]\/)(?!\/)/).map((part, j) => (
                    <span key={j}>
                      {j > 0 && <wbr />}
                      {part}
                    </span>
                  ))
                : line}
            </span>
          </div>
        ))}
      </pre>
    </div>
  );
}
